#!/usr/bin/env bash
set -euo pipefail

BIN=${1:-./build/shape_gemm}

shapes=(
  "8 4096 4096"
  "16 4096 4096"
  "32 4096 4096"
  "64 4096 4096"
  "128 4096 4096"
  "256 4096 4096"
  "512 4096 4096"
  "4096 8 4096"
  "4096 16 4096"
  "4096 32 4096"
  "512 512 512"
  "1024 1024 1024"
  "2048 2048 2048"
)

for shape in "${shapes[@]}"; do
  echo "============================================================"
  echo "$shape"
  "$BIN" $shape --all-kernels
done
